function mutations(route) {
  const cloned = JSON.parse(JSON.stringify(route || {}));
  cloned.mutations_applied = [
    {
      type: "solvent_step_1",
      original: cloned.steps?.[0]?.conditions?.solvent || "unknown",
      new: "2-MeTHF",
      reason: "Improves process safety and solvent recovery in demo mode.",
    },
  ];
  cloned.mutation_count = 1;
  if (cloned.steps?.[0]?.conditions) cloned.steps[0].conditions.solvent = "2-MeTHF";
  return cloned;
}

function json(status, body) {
  return {
    status,
    headers: {
      "content-type": "application/json",
      "access-control-allow-origin": "*",
      "access-control-allow-methods": "GET,POST,OPTIONS",
      "access-control-allow-headers": "content-type,x-api-key",
    },
    body: JSON.stringify(body),
  };
}

function readBody(req) {
  return new Promise((resolve) => {
    let raw = "";
    req.on("data", (chunk) => {
      raw += chunk;
    });
    req.on("end", () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch {
        resolve({});
      }
    });
  });
}

