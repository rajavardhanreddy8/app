const server = http.createServer(async (req, res) => {
  try {
    const response = await route(req);
    res.writeHead(response.status, response.headers);
    res.end(response.status === 204 ? "" : response.body);
  } catch (error) {
    const response = json(500, { detail: error.message || "Demo API error" });
    res.writeHead(response.status, response.headers);
    res.end(response.body);
  }
});

server.listen(PORT, () => {
  console.log(`SynthAI demo API listening on http://localhost:${PORT}`);
});
