function isLikelySmiles(smiles) {
  const s = String(smiles || "").trim();
  if (!s) return false;
  if (!/^[A-Za-z0-9@+\-=\\/()[\]#%.,:]+$/.test(s)) return false;
  let balance = 0;
  for (const ch of s) {
    if (ch === "(" || ch === "[") balance += 1;
    if (ch === ")" || ch === "]") balance -= 1;
    if (balance < 0) return false;
  }
  return balance === 0;
}

function moleculeInfo(smiles) {
  const s = String(smiles || "").trim();
  const known = COMMON_MOLECULES[s];
  if (known) return { valid: true, canonical_smiles: s, ...known };
  if (!isLikelySmiles(s)) return { valid: false, error: "Invalid SMILES syntax" };
  const atoms = (s.match(/[A-Z][a-z]?|[cnops]/g) || []).length || 1;
  const hetero = (s.match(/[NOSnos]/g) || []).length;
  return {
    valid: true,
    name: "Demo molecule",
    canonical_smiles: s,
    molecular_formula: "Demo",
    molecular_weight: Math.round((atoms * 12.4 + hetero * 8) * 100) / 100,
    logp: Math.round((1.2 + atoms * 0.12 - hetero * 0.25) * 100) / 100,
    tpsa: Math.round(hetero * 18.5 * 100) / 100,
    h_donors: Math.min(hetero, 3),
    h_acceptors: Math.min(hetero + 1, 8),
    rotatable_bonds: Math.max(0, Math.min(8, Math.floor(atoms / 4))),
    num_atoms: atoms,
    num_bonds: Math.max(0, atoms - 1),
    lipinski_violations: 0,
  };
}

